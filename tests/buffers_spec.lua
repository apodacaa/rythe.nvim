local helpers = require("tests.helpers")
local cli = require("rythe.cli")
local buffers = require("rythe.buffers")

local function set(lines)
  vim.api.nvim_buf_set_lines(0, 0, -1, false, lines)
end

local function lines()
  return vim.api.nvim_buf_get_lines(0, 0, -1, false)
end

describe("journal buffers", function()
  local notes

  before_each(function()
    notes = helpers.capture_notify()
    vim.cmd("silent! %bwipeout!")
    require("rythe").setup({})
    helpers.temp_journal()
  end)

  it("new: :w creates the entry and the buffer becomes rythe://<id>", function()
    buffers.new()
    assert.are.equal("rythe://new", vim.api.nvim_buf_get_name(0))
    set({ "first line", "", "more #work" })
    vim.cmd.write()

    local entries = cli.json({ "list" })
    assert.are.equal(1, #entries)
    assert.are.equal("first line\n\nmore #work\n", entries[1].body)
    assert.are.equal("rythe://" .. entries[1].id, vim.api.nvim_buf_get_name(0))
    assert.is_false(vim.bo.modified)
    assert.are.equal(-1, vim.fn.bufnr("rythe://new")) -- no leftover buffer

    -- the next :w edits that entry rather than making another
    set({ "first line, changed" })
    vim.cmd.write()
    entries = cli.json({ "list" })
    assert.are.equal(1, #entries)
    assert.are.equal("first line, changed\n", entries[1].body)
    assert.is_not_nil(entries[1].updated)
  end)

  it("new: after :w says only that it saved, however old the journal is", function()
    helpers.seed(os.date("%Y-%m-%dT08:00:00", os.time() - 7 * 86400), "from last week")
    buffers.new()
    set({ "today" })
    vim.cmd.write()
    assert.is_truthy(notes[#notes].msg:find("^saved "))
  end)

  it("new: a blank :w creates nothing and keeps the buffer", function()
    buffers.new()
    set({ "", "  " })
    vim.cmd.write()
    assert.are.same({}, cli.json({ "list" }))
    assert.are.equal("rythe://new", vim.api.nvim_buf_get_name(0))
    assert.is_true(vim.bo.modified)
    assert.are.equal(vim.log.levels.ERROR, notes[#notes].level)
    assert.are.equal("no entry created (empty)", notes[#notes].msg)
  end)

  it("new: goes back to an unsaved draft instead of starting over", function()
    buffers.new()
    set({ "draft" })
    vim.cmd.enew()
    buffers.new()
    assert.are.same({ "draft" }, lines())
  end)

  it("open: loads the body by any ref and :w edits it", function()
    local id = helpers.seed("2026-09-30T16:46:08", "line one\nline two")
    buffers.open("last")
    assert.are.equal("rythe://" .. id, vim.api.nvim_buf_get_name(0))
    assert.are.same({ "line one", "line two" }, lines())
    assert.is_false(vim.bo.modified)

    set({ "line one", "line two", "line three" })
    vim.cmd.write()
    assert.are.equal("line one\nline two\nline three\n", cli.json({ "show", id }).body)
    assert.is_false(vim.bo.modified)
  end)

  it("open: a refused edit (empty text) leaves the entry and the buffer modified", function()
    local id = helpers.seed("2026-09-30T16:46:08", "keep me")
    buffers.open(id)
    set({ "" })
    vim.cmd.write()
    assert.are.equal("keep me", vim.trim(cli.json({ "show", id }).body))
    assert.is_true(vim.bo.modified)
    assert.is_truthy(notes[#notes].msg:find("entry left empty"))
  end)

  it(":e rythe://<id> and :e! read through the CLI", function()
    local id = helpers.seed("2026-09-30T16:46:08", "from the cli")
    vim.cmd.edit("rythe://" .. id)
    assert.are.same({ "from the cli" }, lines())
    set({ "scratch" })
    vim.cmd("edit!")
    assert.are.same({ "from the cli" }, lines())
  end)

  it("sets up the buffer for writing", function()
    buffers.new()
    assert.are.equal("acwrite", vim.bo.buftype)
    assert.are.equal("markdown", vim.bo.filetype)
    assert.are.equal("", vim.bo.spellcapcheck)
    assert.is_false(vim.b.completion)
    assert.is_false(vim.bo.swapfile)
  end)
end)

describe("prompted entries", function()
  before_each(function()
    helpers.capture_notify()
    vim.cmd("silent! %bwipeout!")
    require("rythe").setup({})
    helpers.temp_journal()
  end)

  it("shows the prompt above the text, saves only the text, then drops the prompt", function()
    buffers.new("What stood out today, and why?")
    assert.are.same({ "What stood out today, and why?", "" }, buffers.guide())
    assert.are.same({ "" }, vim.api.nvim_buf_get_lines(0, 0, -1, false))
    vim.api.nvim_buf_set_lines(0, 0, -1, false, { "the rain" })
    vim.cmd.write()
    assert.are.equal("the rain\n", cli.json({ "show", "last" }).body)
    assert.are.same({}, buffers.guide())
  end)

  it("wraps a long prompt", function()
    vim.cmd("vsplit | vertical resize 30")
    buffers.new(("word "):rep(20))
    local guide = buffers.guide()
    assert.is_true(#guide > 2)
    for _, line in ipairs(guide) do
      assert.is_true(#line <= 26)
    end
  end)
end)
