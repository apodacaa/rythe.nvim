local helpers = require("tests.helpers")
local cli = require("journal.cli")

describe("cli.json", function()
  before_each(function()
    require("journal").setup({})
    helpers.temp_journal()
  end)

  it("decodes a list of entries", function()
    local id = helpers.seed("2026-09-30T16:46:08", "first entry #work")
    local entries, err = cli.json({ "list" })
    assert.is_nil(err)
    assert.are.equal(1, #entries)
    assert.are.equal(id, entries[1].id)
    assert.are.same({ "work" }, entries[1].tags)
    assert.is_nil(entries[1].updated) -- JSON null becomes nil
  end)

  it("sends stdin and returns the new entry", function()
    local entry, err = cli.json({ "new" }, { stdin = "from stdin\n" })
    assert.is_nil(err)
    assert.are.equal("from stdin\n", entry.body)
  end)

  it("returns the exit code and message on failure", function()
    local data, err = cli.json({ "show", "nope" })
    assert.is_nil(data)
    assert.are.equal(2, err.code)
    assert.is_falsy(err.message:find("^journal: "))
    assert.is_truthy(#err.message > 0)
  end)

  it("reports a missing CLI instead of throwing", function()
    require("journal").setup({ cmd = "journal-does-not-exist" })
    local data, err = cli.json({ "list" })
    assert.is_nil(data)
    assert.are.equal(-1, err.code)
  end)
end)
